_KIND_NAME = re.compile(r"[a-z][a-z0-9_]*")
_MISSING = object()


@dataclass(frozen=True)
class Tags:
    """One entry's Tags after the review: each field the reviewed value where ``tags.toml``
    gives one (``reviewed``, confidence 1), else the proposal."""

    category: str
    kind: str
    mount: str
    set: str
    era: str
    collision: str
    suits: Tuple[str, ...]
    use: str
    confidence: Mapping[str, float] = field(default_factory=dict)
    why: Mapping[str, str] = field(default_factory=dict)
    reviewed: Tuple[str, ...] = ()
    note: str = ""

    @property
    def lowest(self) -> float:
        """The entry's confidence: its least sure Tag (``use`` aside: ``review`` is a
        default, not a claim)."""
        return min((self.confidence.get(f, 0.0) for f in TAG_FIELDS if f != "use"), default=0.0)


@dataclass(frozen=True)
class Model:
    key: str
    name: str
    archive: str
    wld: str
    animation: str
    measured: Mapping[str, Any]
    observed: Optional[Mapping[str, Any]]
    placed: Mapping[str, int]
    textures: Tuple[Mapping[str, Any], ...]
    tags: Tags

    @property
    def placed_total(self) -> int:
        return sum(self.placed.values())


@dataclass(frozen=True)
class Catalogue:
    models: Mapping[str, Model]
    kinds: Mapping[str, str]
    sets: Tuple[str, ...]

    def usable(self) -> Dict[str, Model]:
        """The models that may enter builds (``use = "yes"``, Req 3.4)."""
        return {k: m for k, m in self.models.items() if m.tags.use == "yes"}

    def find(self, use: Optional[str] = "yes", **want: str) -> Dict[str, Model]:
        """Models whose Tags equal every ``want`` (``kind="table", set="gnoll"``); ``suits``
        matches when the model's suits hold it."""
        out = {}
        for k, m in self.models.items():
            if use is not None and m.tags.use != use:
                continue
            if all((v in m.tags.suits) if f == "suits" else getattr(m.tags, f) == v
                   for f, v in want.items()):
                out[k] = m
        return out


# --- checking one Tag value ------------------------------------------------------------------


class _Relabel:
    """A checker that files every failure under one field name."""

    def __init__(self, chk: _Checker, label: str):
        self.chk, self.label = chk, label

    def fail(self, where: str, _fld: str, *a, **k) -> None:
        self.chk.fail(where, self.label, *a, **k)


def _check_value(chk: _Checker, where: str, fld: str, v: Any, kinds: Mapping[str, str],
                 sets: Tuple[str, ...], label: Optional[str] = None) -> Any:
    """The value if good, else ``_MISSING`` (with the failure recorded under ``label``,
    default ``fld``)."""
    if label:
        chk = _Relabel(chk, label)
    allowed = {"category": CATEGORIES, "mount": MOUNTS, "set": sets, "era": ERAS,
               "collision": COLLISIONS, "use": USES}
    if fld == "kind":
        if isinstance(v, str) and v in kinds:
            return v
        chk.fail(where, fld, v, "a kind (" + ", ".join(sorted(kinds)) + "; or add it to tags.toml's kinds)")
        return _MISSING
    if fld == "suits":
        if not isinstance(v, list):
            chk.fail(where, fld, v, 'an array like ["dungeon", "barracks"]')
            return _MISSING
        bad = [x for x in v if not isinstance(x, str) or x not in SUITS]
        if bad:
            chk.fail(where, fld, bad[0], _one_of(SUITS))
            return _MISSING
        return tuple(dict.fromkeys(v))
    if fld == "note":
        if isinstance(v, str):
            return v
        chk.fail(where, fld, v, "a string")
        return _MISSING
    if isinstance(v, str) and v in allowed[fld]:
        return v
    chk.fail(where, fld, v, _one_of(allowed[fld]))
    return _MISSING


# --- loading -----------------------------------------------------------------------------------


def read_reviews(path: Path, keys=None, chk: Optional[_Checker] = None):
    """``tags.toml`` as ({key: {field: value}}, kinds, sets), checked; ``keys`` is the
    catalogue's entries (a review naming another entry fails). Raises ``RuleSetError``
    unless ``chk`` is given to collect into."""
    own = chk is None
    chk = chk or _Checker(TAGS_FILE)
    data = _read_toml(Path(path), chk)
    reviews: Dict[str, Dict[str, Any]] = {}
    kinds = dict(KINDS)
    sets = SETS
    if data is not None:
        chk.keys(data, "top level", ("kinds", "sets", "models"))
        extra = data.get("kinds", {})
        if not isinstance(extra, dict):
            chk.fail("kinds", "kinds", extra, 'a table like { lever = "other" }')
            extra = {}
        for k, c in extra.items():
            if not _KIND_NAME.fullmatch(k):
                chk.fail("kinds", k, k, "a kind name: lowercase letters, digits and _", raw=False)
            elif c not in CATEGORIES:
                chk.fail("kinds", k, c, _one_of(CATEGORIES))
            else:
                kinds[k] = c
        extra_sets = data.get("sets", [])
        if not isinstance(extra_sets, list):
            chk.fail("sets", "sets", extra_sets, 'an array like ["centaur"]')
            extra_sets = []
        for s in extra_sets:
            if isinstance(s, str) and _KIND_NAME.fullmatch(s):
                if s not in sets:
                    sets = sets + (s,)
            else:
                chk.fail("sets", "sets", s, "a Set name: lowercase letters, digits and _")
        models = data.get("models", {})
        if not isinstance(models, dict):
            chk.fail("models", "models", models, '[models] with lines like "NAME" = { use = "yes" }')
            models = {}
        for key, body in models.items():
            where = f"models.{key}"
            if keys is not None and key not in keys:
                chk.fail(where, "entry", key, "an entry of catalogue.json (a model's key, "
                         "NAME or NAME@zone)")
                continue
            if not isinstance(body, dict):
                chk.fail(where, "entry", body, 'an inline table like { use = "yes" }')
                continue
            chk.keys(body, where, TAG_FIELDS + ("note",))
            got = {}
            for fld, v in body.items():
                if fld not in TAG_FIELDS + ("note",):
                    continue
                ok = _check_value(chk, where, fld, v, kinds, sets)
                if ok is not _MISSING:
                    got[fld] = ok
            if "kind" in got and "category" in got and kinds[got["kind"]] != got["category"]:
                chk.fail(where, "category", got["category"],
                         f'"{kinds[got["kind"]]}", the Category of kind "{got["kind"]}"')
            reviews[key] = got
    if own:
        chk.raise_if_failed()
    return reviews, kinds, sets


def _proposed(chk: _Checker, key: str, entry: Mapping[str, Any], kinds, sets) -> Optional[Dict[str, Any]]:
    tags = entry.get("tags")
    if not isinstance(tags, dict):
        chk.fail(key, "tags", tags if tags is not None else _MISSING,
                 "the proposed Tags (run scripts/prop_catalogue.py tag)")
        return None
    out = {}
    for fld in TAG_FIELDS:
        if fld not in tags:
            chk.fail(key, f"tags.{fld}", _MISSING, "a proposed value (run scripts/prop_catalogue.py tag)")
            continue
        v = _check_value(chk, key, fld, tags[fld], kinds, sets, label=f"tags.{fld}")
        if v is not _MISSING:
            out[fld] = v
    conf = tags.get("conf", {})
    if not isinstance(conf, dict) or any(not isinstance(conf.get(f), (int, float)) or not 0 <= conf[f] <= 1
                                         for f in TAG_FIELDS):
        chk.fail(key, "tags.conf", conf, "a confidence from 0 to 1 for every Tag")
    out["conf"] = conf if isinstance(conf, dict) else {}
    out["why"] = tags.get("why", {}) if isinstance(tags.get("why", {}), dict) else {}
    return out if len(out) == len(TAG_FIELDS) + 2 else None


def merge(proposed: Mapping[str, Any], review: Mapping[str, Any], kinds: Mapping[str, str]) -> Tags:
    """One entry's Tags: the review's fields win; a reviewed kind brings its Category."""
    vals = {f: proposed[f] for f in TAG_FIELDS}
    vals.update({f: v for f, v in review.items() if f in TAG_FIELDS})
    reviewed = [f for f in TAG_FIELDS if f in review]
    if "kind" in review and "category" not in review:
        vals["category"] = kinds[review["kind"]]
        reviewed.append("category")
    conf = {f: (1.0 if f in reviewed else float(proposed["conf"].get(f, 0.0))) for f in TAG_FIELDS}
    return Tags(category=vals["category"], kind=vals["kind"], mount=vals["mount"], set=vals["set"],
                era=vals["era"], collision=vals["collision"], suits=tuple(vals["suits"]), use=vals["use"],
                confidence=conf, why=dict(proposed.get("why", {})),
                reviewed=tuple(f for f in TAG_FIELDS if f in reviewed), note=review.get("note", ""))


def load(catalogue: Path = DECOR_DIR / CATALOGUE_FILE, tags: Path = DECOR_DIR / TAGS_FILE) -> Catalogue:
    """Load the catalogue and its reviews, checked strictly: raises ``RuleSetError`` naming
    every bad value by file, entry and field, in either file."""
    c_chk, t_chk = _Checker(CATALOGUE_FILE), _Checker(TAGS_FILE)
    try:
        cat = json.loads(Path(catalogue).read_text(encoding="utf-8"))
    except FileNotFoundError:
        c_chk.fail("file", "path", str(catalogue), "an existing catalogue (scripts/prop_catalogue.py build)")
        raise RuleSetError(c_chk.errors)
    except ValueError as exc:
        c_chk.fail("file", "json", str(exc), "valid JSON")
        raise RuleSetError(c_chk.errors)
    entries = cat.get("models", {}) if isinstance(cat, dict) else {}
    reviews, kinds, sets = read_reviews(Path(tags), set(entries), t_chk)
    models = {}
    for key, e in entries.items():
        prop = _proposed(c_chk, key, e, kinds, sets)
        if prop is None:
            continue
        src = e.get("source", {})
        models[key] = Model(
            key=key, name=e.get("name", key.split("@")[0]), archive=src.get("archive", ""),
            wld=src.get("wld", ""), animation=e.get("animation", "static"),
            measured=e.get("measured", {}), observed=e.get("observed"),
            placed=dict(e.get("placed", {}).get("zones", {})),
            textures=tuple(e.get("textures", ())),
            tags=merge(prop, reviews.get(key, {}), kinds))
    errors: list[CheckError] = c_chk.errors + t_chk.errors
    if errors:
        raise RuleSetError(errors)
    return Catalogue(models=models, kinds=kinds, sets=sets)


# --- the line a review pastes ----------------------------------------------------------------------


def _toml(v: Any) -> str:
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_toml(x) for x in v) + "]"
    return json.dumps(v)


def review_line(key: str, values: Mapping[str, Any]) -> str:
    """The ``tags.toml`` line (under ``[models]``) setting ``values`` for ``key``."""
    body = ", ".join(f"{f} = {_toml(values[f])}" for f in TAG_FIELDS + ("note",) if f in values)
    return f"{json.dumps(key)} = {{ {body} }}"


def parse_line(line: str) -> Dict[str, Any]:
    """A review line read back (for tests and the sheet's own check)."""
    return tomllib.loads(line)
