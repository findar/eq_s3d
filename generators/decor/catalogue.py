"""The stock model catalogue with its Tags (roadmap step 11, Req 3; design "The catalogue").

Two files, loaded and checked together:

- ``rules/decor/catalogue.json``: generated by ``scripts/prop_catalogue.py``: per model its
  measured and observed fields and the auto-tagger's proposed Tags (``tags``), each with a
  confidence (``tags.conf``) and a short reason (``tags.why``);
- ``rules/decor/tags.toml``: reviewed Tags, written by a person, keyed by catalogue entry.
  A reviewed field wins over the proposed one; fields the review leaves out keep the
  proposal. The catalogue's rebuild never writes this file, so a rebuild can't lose a
  review.

Every Tag value is checked strictly, in both files; every bad value is named by file, entry
and field (``RuleSetError``, as step 9's loaders). A model enters builds only with
``use = "yes"`` (Req 3.4), which only a review sets (archive decisions 4 and 5).

``tags.toml``::

    kinds = { lever = "other" }      # optional: kinds beyond KINDS, with their Category
    sets = ["centaur"]               # optional: Sets beyond SETS

    [models]
    "TORCHPOINT" = { kind = "torch", mount = "wall", use = "yes" }
    "CHAIR@freportw" = { use = "no", note = "a variant with a broken seat" }
"""

